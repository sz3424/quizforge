export type QuestionType = 'multiple_choice' | 'true_false' | 'short_answer';
export type Difficulty = 'easy' | 'medium' | 'hard' | 'mixed';

export interface DocumentPage {
  id: number;
  page_number: number;
  text?: string | null;
}

export interface Document {
  id: number;
  original_filename: string;
  file_size?: number | null;
  page_count?: number | null;
  extraction_status: string;
  created_at: string;
  updated_at: string;
  /** Returned by GET /api/documents/{id}/pages */
  pages?: DocumentPage[];
  total_characters?: number;
  total_words?: number;
}

export interface Question {
  id: number;
  quiz_id?: number;
  text: string;
  type: QuestionType;
  difficulty?: string | null;
  options?: string[] | null;
  correct_answer?: string | null;
  explanation?: string | null;
  source_pages?: number[] | null;
  source_excerpt?: string | null;
  order: number;
}

export interface AttemptAnswer {
  id?: number;
  attempt_id?: number;
  question_id: number;
  /** Denormalized by the backend so Analytics/Results need only this endpoint. */
  question_type?: QuestionType;
  question_text?: string;
  submitted_answer?: string | null;
  correctness?: boolean;
  awarded_marks?: number;
  reviewed?: boolean;
}

export interface Attempt {
  id: number;
  quiz_id: number;
  quiz_title?: string;
  started_at: string;
  submitted_at?: string | null;
  status: 'in_progress' | 'completed';
  score?: number | null;
  max_score?: number | null;
  percentage?: number | null;
  duration_seconds?: number | null;
  answers?: AttemptAnswer[];
  quiz?: Quiz;
}

export interface QuizConfig {
  question_count?: number;
  question_types?: QuestionType[];
  topic_pages?: number[];
  shuffle_questions?: boolean;
  shuffle_options?: boolean;
  show_explanations?: boolean;
  show_source_pages?: boolean;
  allow_skip?: boolean;
  allow_retry?: boolean;
  timer_minutes?: number | null;
  /** Set when generated by the offline fallback instead of an LLM provider. */
  generation_method?: 'ai' | 'offline';
  provider_label?: string;
}

export interface Quiz {
  id: number;
  title: string;
  document_id: number;
  difficulty?: Difficulty | string | null;
  config?: QuizConfig | null;
  generation_method?: string;
  created_at: string;
  updated_at: string;
  question_count?: number;
  document?: Document;
  questions?: Question[];
  attempts?: Attempt[];
}

export interface AttemptResults {
  attempt: Attempt;
  quiz: Quiz;
  questions: Question[];
  answers: AttemptAnswer[];
  correct_count: number;
  incorrect_count: number;
  unanswered_count: number;
}

export interface ProviderStatus {
  configured: boolean;
  provider: string;
  model: string;
  api_base: string;
  message: string;
  missing_variables: string[];
}